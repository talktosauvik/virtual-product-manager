def sanitize_telemetry_payload(payload: dict[str, Any]) -> dict[str, Any]:
    """Scrub PCI-DSS v4.0 (PAN, SSN) & CareCredit HIPAA (MRN, ICD-10) tokens via json.dumps + regex (NEVER eval())."""
