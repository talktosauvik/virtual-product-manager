PAN_REGEX = re.compile(r"\b(?:\d[ -]*?){13,16}\b")
SSN_REGEX = re.compile(r"\b\d{3}-\d{2}-\d{4}\b")
MRN_REGEX = re.compile(r"\bMRN-\d{6,10}\b")
ICD10_REGEX = re.compile(r"\b[A-TV-Z][0-9][0-9AB](?:\.[0-9A-TV-Z]{1,4})?\b")


def sanitize_telemetry_payload_live(payload: dict[str, Any]) -> tuple[dict[str, Any], dict[str, int]]:
    """Deterministic JSON serialization + compiled regex redaction for PCI-DSS v4.0 & CareCredit HIPAA (zero eval())."""
    raw_json = json.dumps(payload)
    counts = {
        "pan_redacted": len(PAN_REGEX.findall(raw_json)),
        "ssn_redacted": len(SSN_REGEX.findall(raw_json)),
        "mrn_redacted": len(MRN_REGEX.findall(raw_json)),
        "icd10_redacted": len(ICD10_REGEX.findall(raw_json)),
    }
    scrubbed = SSN_REGEX.sub("[REDACTED_SSN]", raw_json)
    scrubbed = MRN_REGEX.sub("[REDACTED_MRN]", scrubbed)
    scrubbed = ICD10_REGEX.sub("[REDACTED_ICD10]", scrubbed)
    scrubbed = PAN_REGEX.sub("[REDACTED_PAN]", scrubbed)
    return json.loads(scrubbed), counts


